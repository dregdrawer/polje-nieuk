    private static let byKind: [String: ModuleSpec] = Dictionary(uniqueKeysWithValues: all.map { ($0.kind, $0) })

    public static func spec(_ kind: String) -> ModuleSpec? { byKind[kind] }

    /// Max-style lookup: "delay", "delay~", "verb", "adc~" all work.
    public static func search(_ query: String) -> [ModuleSpec] {
        let q = query.lowercased().replacingOccurrences(of: "~", with: "").trimmingCharacters(in: .whitespaces)
        if q.isEmpty { return all }
        func names(_ s: ModuleSpec) -> [String] {
            [s.kind, s.name.replacingOccurrences(of: "~", with: "")] + s.aliases
        }
        let prefix = all.filter { names($0).contains { $0.hasPrefix(q) } }
        let other = all.filter { s in
            !prefix.contains { $0.kind == s.kind }
                && (names(s).contains { $0.contains(q) } || s.summary.lowercased().contains(q))
        }
        return prefix + other
    }
